type BenchHubEntityRow = {
  id: string;
  entity_type: string;
  canonical_name: string;
  description: string | null;
  zh_description: string | null;
  homepage_url: string | null;
  record_url: string | null;
  record_summary: string | null;
  source_slugs: string[] | null;
  task_slugs: string[] | null;
  domain_slugs: string[] | null;
  modality_slugs: string[] | null;
  language_slugs: string[] | null;
};

type SourceRecordIdRow = {
  id: string;
  source_slug: string;
  external_id: string;
};

type IndexedEntity = {
  entity: LibraryEntityInput;
  recordId: string;
  sourceSlug: string;
  sourceRecordId: string;
  tags: LibraryTagInput[];
};

/**
 * Search existing BenchHub entities and return them as AutoFind candidates.
 *
 * @param queries AutoFind search queries generated by the model/rules.
 * @param input Discovery profile and sample target counts.
 * @returns Ranked BenchHub candidates, or an empty list when BenchHub is unavailable.
 */
export async function searchBenchHubCandidates(
  queries: string[],
  input: AutoFindDiscoveryInput,
): Promise<DatasetCandidate[]> {
  const projectRef = resolveBenchHubProjectRef();
  await ensureBenchHubReady(projectRef);

  const searchText = [input.searchProfile, ...queries].join(" ").slice(0, 1200);
  const rows = await runLibraryQuery<BenchHubEntityRow[]>({
    projectRef,
    readOnly: true,
    query: `
      select
        e.id,
        e.entity_type,
        e.canonical_name,
        e.description,
        e.zh_description,
        e.homepage_url,
        r.source_url as record_url,
        r.summary as record_summary,
        coalesce(array_agg(distinct t.slug) filter (where t.tag_type = 'source'), array[]::text[]) as source_slugs,
        coalesce(array_agg(distinct t.slug) filter (where t.tag_type = 'task'), array[]::text[]) as task_slugs,
        coalesce(array_agg(distinct t.slug) filter (where t.tag_type = 'domain'), array[]::text[]) as domain_slugs,
        coalesce(array_agg(distinct t.slug) filter (where t.tag_type = 'modality'), array[]::text[]) as modality_slugs,
        coalesce(array_agg(distinct t.slug) filter (where t.tag_type = 'language'), array[]::text[]) as language_slugs
      from library_entities e
      left join library_source_records r on r.id = e.primary_record_id
      left join library_entity_tags et on et.entity_id = e.id
      left join library_tags t on t.id = et.tag_id
      where
        e.entity_type in ('dataset', 'benchmark', 'repository', 'collection')
        and (
          e.canonical_name ilike any($1::text[])
          or coalesce(e.description, '') ilike any($1::text[])
          or coalesce(e.zh_description, '') ilike any($1::text[])
          or coalesce(e.search_text_zh, '') ilike any($1::text[])
          or exists (
            select 1
            from library_entity_tags etq
            join library_tags tq on tq.id = etq.tag_id
            where etq.entity_id = e.id
              and (
                tq.slug ilike any($1::text[])
                or tq.label ilike any($1::text[])
                or coalesce(tq.label_zh, '') ilike any($1::text[])
              )
          )
        )
      group by e.id, r.source_url, r.summary
      order by e.updated_at desc, e.canonical_name asc
      limit 16;
    `,
    parameters: [buildBenchHubSearchPatterns(searchText)],
  });

  return rows
    .map((row) => mapBenchHubEntityToCandidate(row, searchText))
    .filter((candidate): candidate is DatasetCandidate => Boolean(candidate));
}

/**
 * Persist newly discovered AutoFind candidates into BenchHub for future searches.
 *
 * @param candidates Candidate list discovered during this AutoFind run.
 * @param input Discovery profile and search context.
 * @returns Indexing counters and non-fatal warnings.
 */
export async function indexAutoFindCandidatesToBenchHub(
  candidates: DatasetCandidate[],
  input: AutoFindDiscoveryInput,
): Promise<{ indexed: number; warnings: string[] }> {
  const indexable = candidates
    .filter((candidate) => candidate.source !== "benchhub")
    .filter((candidate) => candidate.url.trim().length > 0)
    .slice(0, 12);
  if (indexable.length === 0) {
    return { indexed: 0, warnings: [] };
  }

  const warnings: string[] = [];
  const projectRef = resolveBenchHubProjectRef();
  await ensureBenchHubReady(projectRef);
  const projectId = await resolveLibraryProjectId(projectRef);

  const bySource = groupCandidatesByLibrarySource(indexable, input);
  const recordRows: SourceRecordIdRow[] = [];

  for (const [sourceSlug, records] of bySource.entries()) {
    try {
      const context = await resolveLibraryContext(projectRef, sourceSlug);
      await upsertLibrarySourceRecordsBatch(projectRef, context.projectId, context.sourceId, records);
      recordRows.push(...(await readSourceRecordIds(projectRef, context.sourceId, sourceSlug, records)));
    } catch (error) {
      warnings.push(`${sourceSlug}: ${formatError(error)}`);
    }
  }

  const recordIdByKey = new Map(recordRows.map((row) => [`${row.source_slug}::${row.external_id}`, row.id]));
  const indexedEntities = indexable
    .map((candidate) => buildIndexedEntity(candidate, input, projectId, recordIdByKey))
    .filter((entity): entity is IndexedEntity => Boolean(entity));
  if (indexedEntities.length === 0) {
    return { indexed: 0, warnings };
  }

  const upserted = await upsertLibraryEntitiesBatch(
    projectRef,
    indexedEntities.map((item) => item.entity),
  );
  const entityIdByKey = new Map(upserted.map((row) => [`${row.entityType}::${row.canonicalKey}`, row.id]));
  const links: LibraryEntityRecordLinkInput[] = [];
  const entityTagLinks: LibraryEntityTagLinkInput[] = [];
  const tags = dedupeTags(indexedEntities.flatMap((item) => item.tags));
  const upsertedTags = await upsertLibraryTagsBatch(projectRef, tags);
  const tagIdByKey = new Map(upsertedTags.map((tag) => [`${tag.tagType}::${tag.slug}`, tag.id]));
  const zhDescriptions: Array<{ id: string; name: string; description: string }> = [];

  for (const item of indexedEntities) {
    const entityId = entityIdByKey.get(`${item.entity.entityType}::${item.entity.canonicalKey}`);
    if (!entityId) continue;
    links.push({
      entityId,
      sourceRecordId: item.sourceRecordId,
      relationType: "same_as",
      confidence: 0.85,
    });
    for (const tag of item.tags) {
      const tagId = tagIdByKey.get(`${tag.tagType}::${tag.slug}`);
      if (tagId) entityTagLinks.push({ entityId, tagId });
    }
    zhDescriptions.push({
      id: entityId,
      name: item.entity.canonicalName,
      description: buildChineseEntityDescription(item.entity, item.sourceSlug),
    });
  }

  await upsertLibraryEntityRecordsBatch(projectRef, links);
  await upsertLibraryEntityTagsBatch(projectRef, entityTagLinks);
  await enrichIndexedEntitiesZh(projectRef, zhDescriptions);

  return { indexed: indexedEntities.length, warnings };
}

/**
 * Convert a BenchHub entity row into an AutoFind candidate.
 *
 * @param row Raw entity search row.
 * @param searchText Current AutoFind search context.
 * @returns Dataset candidate or null when no usable URL exists.
 */
export function mapBenchHubEntityToCandidate(
  row: BenchHubEntityRow,
  searchText: string,
): DatasetCandidate | null {
  const url = row.homepage_url ?? row.record_url;
  if (!url) return null;
  return {
    id: `benchhub:${row.id}`,
    source: "benchhub",
    title: row.canonical_name,
    description: row.zh_description ?? row.description ?? row.record_summary ?? "",
    url,
    downloadUrl: row.record_url ?? row.homepage_url ?? undefined,
    score: 12 + scoreTextOverlap(
      [
        row.canonical_name,
        row.description ?? "",
        row.zh_description ?? "",
        ...(row.task_slugs ?? []),
        ...(row.domain_slugs ?? []),
        ...(row.modality_slugs ?? []),
        ...(row.language_slugs ?? []),
      ].join(" "),
      extractSimpleKeywords(searchText),
    ),
  };
}

/**
 * Map one AutoFind candidate to a BenchHub source record payload.
 *
 * @param candidate AutoFind candidate.
 * @param input Discovery profile and search context.
 * @returns Source record payload.
 */
export function mapCandidateToLibrarySourceRecord(
  candidate: DatasetCandidate,
  input: AutoFindDiscoveryInput,
): LibrarySourceRecordInput {
  const text = `${candidate.title} ${candidate.description} ${candidate.url}`;
  const recordKind = inferRecordKind(text);
  const risk = inferRisk(candidate);

  return {
    externalId: buildExternalId(candidate),
    recordKind,
    title: candidate.title,
    summary: candidate.description || null,
    sourceUrl: candidate.url,
    canonicalUrl: candidate.url,
    accessStatus: "public",
    licenseName: null,
    languages: inferLanguages(text),
    taskTypes: inferTaskTypes(text, input),
    modalities: inferModalities(text),
    domains: inferDomains(text, input),
    fileFormats: inferFileFormats(candidate.downloadUrl ?? candidate.url),
    sizeHint: null,
    hasDownload: Boolean(candidate.downloadUrl || /huggingface\.co\/datasets|github\.com/i.test(candidate.url)),
    hasSamples: Boolean(candidate.description),
    commercialRisk: risk,
    redistributionRisk: risk,
    sourceCreatedAt: null,
    sourceUpdatedAt: null,
    rawPayload: candidate,
    metadata: {
      source: "autofind",
      candidateSource: candidate.source,
      score: candidate.score,
      downloadUrl: candidate.downloadUrl ?? null,
      searchProfile: input.searchProfile.slice(0, 1200),
    },
  };
}

async function ensureBenchHubReady(projectRef: string): Promise<void> {
  await ensureLibrarySchema(projectRef);
  await ensureLibraryProject(projectRef, "Zeval Eval Library");
  await seedDefaultLibrarySources(projectRef);
}

function resolveBenchHubProjectRef(): string {
  return process.env.SUPABASE_PROJECT_REF?.trim() || "xlmnrqnwfypvfnddbjhw";
}

function buildBenchHubSearchPatterns(searchText: string): string[] {
  const keywords = extractSimpleKeywords(searchText).slice(0, 12);
  return keywords.length > 0 ? keywords.map((keyword) => `%${keyword}%`) : ["%%"];
}

function groupCandidatesByLibrarySource(
  candidates: DatasetCandidate[],
  input: AutoFindDiscoveryInput,
): Map<string, LibrarySourceRecordInput[]> {
  const grouped = new Map<string, LibrarySourceRecordInput[]>();
  for (const candidate of candidates) {
    const sourceSlug = inferLibrarySourceSlug(candidate);
    const existing = grouped.get(sourceSlug) ?? [];
    existing.push(mapCandidateToLibrarySourceRecord(candidate, input));
    grouped.set(sourceSlug, existing);
  }
  return grouped;
}

async function readSourceRecordIds(
  projectRef: string,
  sourceId: string,
  sourceSlug: string,
  records: LibrarySourceRecordInput[],
): Promise<SourceRecordIdRow[]> {
  return runLibraryQuery<SourceRecordIdRow[]>({
    projectRef,
    readOnly: true,
    query: `
      select id, $2::text as source_slug, external_id
      from library_source_records
      where source_id = $1
        and external_id = any($3::text[]);
    `,
    parameters: [sourceId, sourceSlug, records.map((record) => record.externalId)],
  });
}

function buildIndexedEntity(
  candidate: DatasetCandidate,
  input: AutoFindDiscoveryInput,
  projectId: string,
  recordIdByKey: Map<string, string>,
): IndexedEntity | null {
  const sourceSlug = inferLibrarySourceSlug(candidate);
  const record = mapCandidateToLibrarySourceRecord(candidate, input);
  const sourceRecordId = recordIdByKey.get(`${sourceSlug}::${record.externalId}`);
  if (!sourceRecordId) return null;

  const entityType = mapRecordKindToEntityType(record.recordKind);
  const entity: LibraryEntityInput = {
    projectId,
    entityType,
    canonicalName: candidate.title,
    canonicalKey: buildCanonicalKey(candidate, entityType),
    description: candidate.description || null,
    homepageUrl: candidate.url,
    primaryRecordId: sourceRecordId,
    accessStatus: "public",
    commercialRisk: record.commercialRisk,
    redistributionRisk: record.redistributionRisk,
    languages: record.languages,
    taskTypes: record.taskTypes,
    modalities: record.modalities,
    domains: record.domains,
    metadata: {
      source: "autofind",
      candidateSource: candidate.source,
      searchProfile: input.searchProfile.slice(0, 1200),
    },
  };

  return {
    entity,
    recordId: record.externalId,
    sourceSlug,
    sourceRecordId,
    tags: buildTagsForRecord(sourceSlug, record),
  };
}

function buildTagsForRecord(sourceSlug: string, record: LibrarySourceRecordInput): LibraryTagInput[] {
  const tags: LibraryTagInput[] = [makeTag("source", sourceSlug)];
  tags.push(makeTag("risk", record.commercialRisk));
  for (const task of record.taskTypes) tags.push(makeTag("task", task));
  for (const domain of record.domains) tags.push(makeTag("domain", domain));
  for (const modality of record.modalities) tags.push(makeTag("modality", modality));
  for (const language of record.languages) tags.push(makeTag("language", language));
  for (const format of record.fileFormats) tags.push(makeTag("format", format));
  return dedupeTags(tags);
}

function makeTag(tagType: LibraryTagInput["tagType"], slug: string): LibraryTagInput {
  const normalizedSlug = normalizeSlug(slug);
  return {
    tagType,
    slug: normalizedSlug,
    label: humanizeSlug(normalizedSlug),
    description: null,
    metadata: { source: "autofind" },
  };
}

function dedupeTags(tags: LibraryTagInput[]): LibraryTagInput[] {
  const seen = new Set<string>();
  return tags.filter((tag) => {
    const key = `${tag.tagType}::${tag.slug}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

async function enrichIndexedEntitiesZh(
  projectRef: string,
  rows: Array<{ id: string; name: string; description: string }>,
): Promise<void> {
  if (rows.length === 0) return;
  await runLibraryQuery({
    projectRef,
    readOnly: false,
    query: `
      with input_rows as (
        select *
        from jsonb_to_recordset($1::jsonb) as row(
          id uuid,
          name text,
          description text
        )
      )
      update library_entities e
      set
        zh_name = coalesce(nullif(e.zh_name, ''), input_rows.name),
        zh_description = coalesce(nullif(e.zh_description, ''), input_rows.description),
        search_text_zh = trim(concat_ws(' ', e.canonical_name, input_rows.name, e.description, input_rows.description)),
        updated_at = now()
      from input_rows
      where e.id = input_rows.id;
    `,
    parameters: [JSON.stringify(rows)],
  });
}

function buildChineseEntityDescription(entity: LibraryEntityInput, sourceSlug: string): string {
  const typeZh = humanizeEntityType(entity.entityType);
  const sourceZh = humanizeSlug(sourceSlug);
  const tasks = entity.taskTypes.length > 0 ? entity.taskTypes.map(humanizeSlug).join("、") : "通用评测";
  return `${entity.canonicalName} 是 AutoFind 新发现并写入 BenchHub 的公开${typeZh}，来源于 ${sourceZh}，适合用于 ${tasks} 场景。商业使用风险为${humanizeRisk(entity.commercialRisk)}，再分发风险为${humanizeRisk(entity.redistributionRisk)}。`;
}

function inferLibrarySourceSlug(candidate: DatasetCandidate): string {
  if (candidate.source === "huggingface" || /huggingface\.co/i.test(candidate.url)) return "huggingface";
  if (candidate.source === "github" || /github\.com/i.test(candidate.url)) return "github";
  return "autofind";
}

function inferRecordKind(text: string): LibrarySourceRecordInput["recordKind"] {
  const normalized = text.toLowerCase();
  if (/\bbenchmark|bench\b/.test(normalized)) return "benchmark";
  if (/\bgithub\.com\b/.test(normalized)) return "repository";
  if (/\bdataset|corpus|data\b/.test(normalized)) return "dataset";
  return "dataset";
}

function mapRecordKindToEntityType(recordKind: LibrarySourceRecordInput["recordKind"]): LibraryEntityType {
  if (recordKind === "benchmark") return "benchmark";
  if (recordKind === "repository") return "repository";
  if (recordKind === "collection") return "collection";
  return "dataset";
}

function buildExternalId(candidate: DatasetCandidate): string {
  if (candidate.id && !candidate.id.startsWith("benchhub:")) return candidate.id.slice(0, 240);
  return normalizeUrlKey(candidate.url) ?? normalizeSlug(candidate.title).slice(0, 240);
}

function buildCanonicalKey(candidate: DatasetCandidate, entityType: LibraryEntityType): string {
  const urlKey = normalizeUrlKey(candidate.url);
  if (urlKey) return `url:${urlKey}`;
  return `${entityType}:${normalizeSlug(candidate.title).slice(0, 180)}`;
}

function normalizeUrlKey(value: string): string | null {
  try {
    const url = new URL(value);
    return `${url.hostname}${url.pathname}`.replace(/\/+$/, "").toLowerCase();
  } catch {
    return null;
  }
}

function inferLanguages(text: string): string[] {
  const normalized = text.toLowerCase();
  const languages = new Set<string>();
  if (/chinese|中文|zh\b|mandarin/.test(normalized)) languages.add("zh");
  if (/english|英文|\ben\b/.test(normalized)) languages.add("en");
  return [...languages];
}

function inferTaskTypes(text: string, input: AutoFindDiscoveryInput): string[] {
  const normalized = `${text} ${input.searchProfile}`.toLowerCase();
  const tasks = new Set<string>(["benchmarking"]);
  if (/dialogue|conversation|chat|对话|多轮/.test(normalized)) tasks.add("dialogue");
  if (/question|answer|qa|问答|题库/.test(normalized)) tasks.add("question-answering");
  if (/support|customer|客服|投诉|complaint/.test(normalized)) tasks.add("customer-service");
  if (/finance|financial|金融/.test(normalized)) tasks.add("finance");
  if (/agent|tool|工具/.test(normalized)) tasks.add("agent-tool-use");
  return [...tasks];
}

function inferModalities(text: string): string[] {
  const normalized = text.toLowerCase();
  if (/image|vision|图像|视觉/.test(normalized)) return ["image"];
  if (/audio|speech|语音/.test(normalized)) return ["audio"];
  if (/video|视频/.test(normalized)) return ["video"];
  if (/table|tabular|表格/.test(normalized)) return ["tabular"];
  return ["text"];
}

function inferDomains(text: string, input: AutoFindDiscoveryInput): string[] {
  const normalized = `${text} ${input.searchProfile}`.toLowerCase();
  const domains = new Set<string>();
  if (/finance|financial|金融/.test(normalized)) domains.add("finance");
  if (/medical|health|医疗|健康/.test(normalized)) domains.add("healthcare");
  if (/legal|law|法律/.test(normalized)) domains.add("legal");
  if (/support|customer|客服|投诉/.test(normalized)) domains.add("customer-service");
  if (/education|exam|考试|教育/.test(normalized)) domains.add("education");
  if (domains.size === 0) domains.add("general");
  return [...domains];
}

function inferFileFormats(url: string): string[] {
  const match = url.match(/\.([a-z0-9]+)(?:[?#]|$)/i);
  if (!match) return [];
  const extension = match[1].toLowerCase();
  return ["json", "jsonl", "csv", "parquet", "zip"].includes(extension) ? [extension] : [];
}

function inferRisk(candidate: DatasetCandidate): LibraryRisk {
  if (candidate.source === "huggingface") return "medium";
  if (candidate.source === "github") return "medium";
  return "unknown";
}

function extractSimpleKeywords(text: string): string[] {
  return [
    ...new Set(
      text
        .toLowerCase()
        .split(/[^a-z0-9\u4e00-\u9fff]+/u)
        .map((part) => part.trim())
        .filter((part) => part.length >= 2)
        .filter((part) => !STOPWORDS.has(part)),
    ),
  ];
}

function scoreTextOverlap(text: string, keywords: string[]): number {
  const normalized = text.toLowerCase();
  return keywords.reduce((score, keyword) => score + (normalized.includes(keyword) ? 1 : 0), 0);
}

function normalizeSlug(value: string): string {
  return value
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9\u4e00-\u9fff]+/gu, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 120) || "unknown";
}

function humanizeSlug(value: string): string {
  return value
    .split(/[-_]/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function humanizeEntityType(value: LibraryEntityType): string {
  const labels: Record<LibraryEntityType, string> = {
    dataset: "数据集",
    benchmark: "基准测试",
    paper: "论文",
    collection: "集合",
    repository: "代码仓库",
    other: "资源",
  };
  return labels[value] ?? "资源";
}

function humanizeRisk(value: LibraryRisk): string {
  const labels: Record<LibraryRisk, string> = {
    low: "低",
    medium: "中",
    high: "高",
    restricted: "受限制",
    unknown: "未知",
  };
  return labels[value] ?? "未知";
}

function formatError(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

const STOPWORDS = new Set([
  "the",
  "and",
  "for",
  "with",
  "dataset",
  "benchmark",
  "conversation",
  "dialogue",
  "data",
  "评测",
  "数据",
  "样本",
  "测试",
  "基准",
]);
